async function seedBurmeseBooks() {
  console.log(`Starting to seed ${burmeseBooks.length} authentic Burmese books...`);

  let addedBooks = 0;
  let addedCopies = 0;
  let addedEResources = 0;

  const locations = [
    'National Library - Myanmar Collection (Floor 1, Stacks A-01)',
    'National Library - Myanmar Literature (Floor 1, Stacks A-04)',
    'MOCHT Cultural Archives - Reference Section (Shelf C-12)',
    'MOCHT Tourism & Heritage Reading Room (Floor 2, Shelf T-08)',
    'Naypyitaw Central Stacks - Literature Division (Floor 2, Shelf L-05)',
    'Yangon Heritage Branch - Rare Books Wing (Shelf M-03)',
  ];

  for (let i = 0; i < burmeseBooks.length; i++) {
    const item = burmeseBooks[i];
    const seq = i + 1;

    // Upsert the Book record
    const book = await prisma.book.upsert({
      where: { isbn: item.isbn },
      update: {
        title: item.title,
        author: item.author,
        publisher: item.publisher,
        publicationYear: item.publicationYear,
        genre: item.genre,
        subject: item.subject,
        description: item.description,
        coverUrl: item.coverUrl,
        edition: item.edition,
        language: item.language,
        maxRentDays: item.maxRentDays,
        originalPrice: item.originalPrice,
      },
      create: {
        isbn: item.isbn,
        title: item.title,
        author: item.author,
        publisher: item.publisher,
        publicationYear: item.publicationYear,
        genre: item.genre,
        subject: item.subject,
        description: item.description,
        coverUrl: item.coverUrl,
        edition: item.edition,
        language: item.language,
        maxRentDays: item.maxRentDays,
        originalPrice: item.originalPrice,
      },
    });
    addedBooks++;

    // Create 2 Physical Copies for each book
    const barcode1 = `MM-${1000 + seq * 2 - 1}`;
    const barcode2 = `MM-${1000 + seq * 2}`;

    const loc1 = locations[(seq * 2 - 1) % locations.length];
    const loc2 = locations[(seq * 2) % locations.length];

    const callNumPrefix = `PL3971.${item.genre.slice(0, 3).toUpperCase()}`;

    await prisma.bookCopy.upsert({
      where: { barcode: barcode1 },
      update: {
        location: loc1,
        status: 'AVAILABLE',
        condition: 'GOOD',
      },
      create: {
        bookId: book.id,
        barcode: barcode1,
        callNumber: `${callNumPrefix}.${seq} c.1`,
        location: loc1,
        status: 'AVAILABLE',
        condition: 'NEW',
        price: item.originalPrice,
      },
    });
    addedCopies++;

    await prisma.bookCopy.upsert({
      where: { barcode: barcode2 },
      update: {
        location: loc2,
        status: 'AVAILABLE',
        condition: 'GOOD',
      },
      create: {
        bookId: book.id,
        barcode: barcode2,
        callNumber: `${callNumPrefix}.${seq} c.2`,
        location: loc2,
        status: 'AVAILABLE',
        condition: 'GOOD',
        price: item.originalPrice,
      },
    });
    addedCopies++;

    // If marked as hasEBook, create EResource if not already present
    if (item.hasEBook) {
      const existingEResource = await prisma.eResource.findFirst({
        where: { bookId: book.id },
      });
      if (!existingEResource) {
        await prisma.eResource.create({
          data: {
            bookId: book.id,
            title: `${item.title} (Digital Edition - PDF)`,
            author: item.author,
            format: 'PDF',
            fileUrl: 'https://www.w3.org/WAI/ER/tests/xhtml/testfiles/resources/pdf/dummy.pdf',
            isOpenAccess: true,
            licenseType: 'National Library Open Access',
          },
        });
        addedEResources++;
      }
    }
  }

  console.log(`Successfully seeded:`);
  console.log(`- ${addedBooks} Burmese books`);
  console.log(`- ${addedCopies} Physical book copies with barcodes`);
  console.log(`- ${addedEResources} E-Book digital editions`);
}

seedBurmeseBooks()
  .catch((e) => {
    console.error('Seeding error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
